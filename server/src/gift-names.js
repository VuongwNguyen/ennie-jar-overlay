const byId = new Map(Object.entries(GIFTS).map(([id, [, vi]]) => [id, vi]));
const byEnglish = new Map(Object.values(GIFTS).map(([en, vi]) => [en.toLowerCase(), vi]));

export function vietnameseGiftName(id, name) {
  return byId.get(String(id ?? "")) ?? byEnglish.get(String(name ?? "").trim().toLowerCase()) ?? name;
}
